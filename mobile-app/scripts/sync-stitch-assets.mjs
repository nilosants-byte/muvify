import fs from "node:fs";
import path from "node:path";

const sourceRoot =
  "C:/Users/Danilo/Documents/testes app/design/stitch_onboarding_2_dark/stitch_onboarding_2_dark";
const targetRoot = "C:/Users/Danilo/Documents/dev/personal-app-backend/mobile-app/assets/stitch-screens";
const manifestTarget =
  "C:/Users/Danilo/Documents/dev/personal-app-backend/mobile-app/src/stitch/stitch-assets.ts";

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function sanitizeKey(name) {
  return name
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-zA-Z0-9_]/g, "_")
    .replace(/_+/g, "_")
    .replace(/^_+|_+$/g, "");
}

function copyPngFolders() {
  ensureDir(targetRoot);

  const folders = fs
    .readdirSync(sourceRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b, "pt-BR"));

  const copied = [];
  for (const folder of folders) {
    const sourcePng = path.join(sourceRoot, folder, "screen.png");
    if (!fs.existsSync(sourcePng)) {
      continue;
    }
    const fileName = `${sanitizeKey(folder)}.png`;
    const destination = path.join(targetRoot, fileName);
    fs.copyFileSync(sourcePng, destination);
    copied.push({
      folder,
      key: sanitizeKey(folder),
      fileName
    });
  }

  return copied;
}

function buildManifest(entries) {
  const lines = [];
  lines.push("/* eslint-disable */");
  lines.push("// AUTO-GENERATED by scripts/sync-stitch-assets.mjs");
  const union = entries.map((entry) => `"${entry.key}"`).join(" | ");
  lines.push(`export type StitchAssetKey = ${union};`);
  lines.push("");
  lines.push("export const STITCH_ASSETS = {");
  for (const entry of entries) {
    lines.push(
      `  "${entry.key}": require("../../assets/stitch-screens/${entry.fileName}") as number,`
    );
  }
  lines.push("} as const;");
  lines.push("");
  lines.push(
    "export const STITCH_KEYS = Object.keys(STITCH_ASSETS) as Array<keyof typeof STITCH_ASSETS>;"
  );
  lines.push("");
  return lines.join("\n");
}

function main() {
  const copied = copyPngFolders();
  ensureDir(path.dirname(manifestTarget));
  const manifest = buildManifest(copied);
  fs.writeFileSync(manifestTarget, manifest, "utf-8");
  // eslint-disable-next-line no-console
  console.log(`Sync concluído. Arquivos: ${copied.length}`);
}

main();
